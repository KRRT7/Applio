"""Generate ``_vendor/modules`` and ``_vendor/deep_live_cam`` from upstream
Deep-Live-Cam and Applio's patches.

Applio's vendored Deep-Live-Cam is hacksider/Deep-Live-Cam at the commit in
``tools/vendoring/dlc-upstream.txt``, moved under the ``_vendor`` namespace
(below), with the patches in ``tools/vendoring/patches/dlc`` applied on top
in name order. Both trees are generated by this script and committed; never
edit them by hand. CI's ``check`` fails when they differ from what the script
generates. The layout follows warpforgedotco/kpip's ``scripts/vendor_pip.py``.

The move under ``_vendor`` (the ``base`` branch below) is mechanical:

- ``modules/`` becomes ``_vendor/modules/``, without the desktop UI files
  (``DROPPED``), and upstream's ``LICENSE`` becomes
  ``_vendor/deep_live_cam/LICENSE``;
- imports are rewritten to the ``_vendor`` namespace (``rewrite_imports``),
  so the code never depends on a top-level ``modules`` package;
- line endings become LF: upstream commits many files with CRLF, Applio
  stores LF. The checkout itself converts nothing (``* -text``), so its
  files are the exact bytes committed on any OS or git configuration.

Usage::

    uv run --no-project scripts/vendor_dlc.py sync               # latest upstream main
    uv run --no-project scripts/vendor_dlc.py sync --commit SHA  # a specific commit
    uv run --no-project scripts/vendor_dlc.py check              # committed trees are current
    uv run --no-project scripts/vendor_dlc.py export             # write build/dlc's commits as patches

``sync`` leaves a git checkout in ``build/dlc`` with three branches:
``upstream`` (Deep-Live-Cam itself), ``base`` (``upstream`` moved under
``_vendor``) and ``applio`` (``base`` plus one commit per patch). To change
the vendored code, commit on ``applio`` (``git rebase -i base`` to edit an
existing patch), then ``export`` and ``sync --commit "$(cat
tools/vendoring/dlc-upstream.txt)"``. When upstream moves and a patch no
longer applies, ``sync`` stops mid-``git am`` in ``build/dlc``: resolve it
there, ``git am --continue``, then ``export`` and ``sync``.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import stat
import subprocess
import sys
import tempfile
from pathlib import Path

UPSTREAM_REPOSITORY = "https://github.com/hacksider/Deep-Live-Cam.git"
# Always its latest commit unless ``--commit`` names another.
UPSTREAM_BRANCH = "main"

REPO_ROOT = Path(__file__).resolve().parents[1]
PATCHES_DIR = REPO_ROOT / "tools" / "vendoring" / "patches" / "dlc"
UPSTREAM_FILE = REPO_ROOT / "tools" / "vendoring" / "dlc-upstream.txt"
WORK_DIR = REPO_ROOT / "build" / "dlc"

# Trees copied out of the checkout, relative to both it and the repository.
# _vendor/__init__.py and _vendor/README.md are Applio's own.
TREES = (Path("_vendor") / "modules", Path("_vendor") / "deep_live_cam")

# Upstream's desktop UI: Applio drives Deep-Live-Cam headless.
DROPPED = (
    "gettext.py",
    "run.py",
    "tkinter_fix.py",
    "ui.json",
    "ui.py",
    "ui_tooltip.py",
)

UPSTREAM_BRANCH_NAME = "upstream"
BASE_BRANCH = "base"
PATCHED_BRANCH = "applio"

# Commits the script makes itself; patches keep their own authors.
GIT_IDENTITY = ("-c", "user.name=Applio vendor_dlc", "-c", "user.email=vendor-dlc@invalid", "-c", "core.autocrlf=false")

_IMPORT_PACKAGE = re.compile(r"^(?P<indent>[ \t]*)import modules[ \t]*(?:#.*)?$")
_IMPORT_SUBMODULE = re.compile(r"^(?P<indent>[ \t]*)import modules\.(?P<name>[\w.]+)[ \t]*(?:#.*)?$")
_FROM_IMPORT = re.compile(r"^(?P<lead>[ \t]*from[ \t]+)modules(?P<rest>(?:\.[\w.]+)?[ \t]+import\b)")


class PatchError(RuntimeError):
    pass


def rewrite_imports(text: str) -> str:
    """Point Deep-Live-Cam's imports at the ``_vendor`` namespace.

    ``from modules[.x] import y`` becomes ``from _vendor.modules[.x] import
    y``. ``import modules`` becomes ``from _vendor import modules``, which
    binds the same name. ``import modules.x.y`` cannot be rewritten in place
    (``import _vendor.modules.x.y`` binds ``_vendor``, not ``modules``), so it
    becomes ``from _vendor import modules`` (once per scope) plus an aliased
    import that loads the submodule; code keeps using ``modules.x.y``.
    """
    out = []
    bound = set()  # indentation levels where ``modules`` is already imported
    for line in text.splitlines(keepends=True):
        body = line.rstrip("\r\n")
        newline = line[len(body):]
        match = _IMPORT_PACKAGE.match(body)
        if match:
            indent = match["indent"]
            bound.add(indent)
            out.append(f"{indent}from _vendor import modules{newline}")
            continue
        match = _IMPORT_SUBMODULE.match(body)
        if match:
            indent, name = match["indent"], match["name"]
            if indent not in bound:
                bound.add(indent)
                out.append(f"{indent}from _vendor import modules  # noqa: F401{newline}")
                # After a blank line (the start of an import group), the
                # namespace import gets its own group, as the original
                # vendoring of this code laid it out.
                if len(out) >= 2 and not out[-2].strip():
                    out.append(newline)
            alias = "_modules_" + "_".join(name.split(".")[-2:])
            out.append(
                f"{indent}import _vendor.modules.{name} as {alias}  # noqa: F401  "
                f"(loads the submodule; vendoring-safe form of `import modules.{name}`){newline}"
            )
            continue
        out.append(_FROM_IMPORT.sub(r"\g<lead>_vendor.modules\g<rest>", body) + newline)
    return "".join(out)


def _git(*args: str, cwd: Path, capture: bool = False) -> str:
    result = subprocess.run(
        ["git", *GIT_IDENTITY, *args],
        cwd=cwd,
        check=True,
        text=True,
        stdout=subprocess.PIPE if capture else None,
    )
    return result.stdout or ""


def _remove_tree(path: Path) -> None:
    """``shutil.rmtree`` that also removes read-only files (git objects on Windows)."""

    def make_writable_and_retry(function, target, _error) -> None:
        os.chmod(target, stat.S_IWRITE)
        function(target)

    if sys.version_info >= (3, 12):
        shutil.rmtree(path, onexc=make_writable_and_retry)
    else:
        shutil.rmtree(path, onerror=make_writable_and_retry)


def resolve_commit() -> str:
    """Upstream's current commit, without fetching anything."""
    output = subprocess.run(
        ["git", "ls-remote", "--exit-code", UPSTREAM_REPOSITORY, f"refs/heads/{UPSTREAM_BRANCH}"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return output.split()[0]


def find_patches(patches_dir: Path = PATCHES_DIR) -> list[Path]:
    """Patches apply in name order, hence the numeric prefixes."""
    return sorted(patches_dir.glob("*.patch")) if patches_dir.is_dir() else []


def move_under_vendor(checkout: Path) -> None:
    """The ``base`` commit: upstream's ``modules`` under ``_vendor``, imports rewritten."""
    (checkout / "_vendor").mkdir()
    _git("mv", "modules", "_vendor/modules", cwd=checkout)
    for name in DROPPED:
        if (checkout / "_vendor" / "modules" / name).exists():
            _git("rm", "--quiet", "-f", f"_vendor/modules/{name}", cwd=checkout)
    (checkout / "_vendor" / "deep_live_cam").mkdir()
    shutil.copyfile(checkout / "LICENSE", checkout / "_vendor" / "deep_live_cam" / "LICENSE")
    for path in (checkout / "_vendor").rglob("*"):
        if not path.is_file():
            continue
        data = path.read_bytes()
        if b"\x00" in data:
            continue  # binary
        text = data.decode("utf-8").replace("\r\n", "\n")
        if path.suffix == ".py":
            text = rewrite_imports(text)
        if text.encode("utf-8") != data:
            path.write_bytes(text.encode("utf-8"))


def generate(commit: str, checkout: Path) -> None:
    """Build the patched checkout at ``checkout`` from upstream ``commit``."""
    # Empty it rather than delete it: on Windows a shell or an editor whose
    # working directory is the checkout keeps the directory itself in use.
    checkout.mkdir(parents=True, exist_ok=True)
    for child in checkout.iterdir():
        if child.is_dir():
            _remove_tree(child)
        else:
            child.chmod(stat.S_IWRITE)
            child.unlink()

    _git("init", "--quiet", cwd=checkout)
    # No line-ending conversion in either direction (see move_under_vendor).
    (checkout / ".git" / "info").mkdir(parents=True, exist_ok=True)
    (checkout / ".git" / "info" / "attributes").write_text("* -text\n", encoding="ascii")
    _git("fetch", "--quiet", "--depth", "1", UPSTREAM_REPOSITORY, commit, cwd=checkout)
    _git("checkout", "--quiet", "-b", UPSTREAM_BRANCH_NAME, "FETCH_HEAD", cwd=checkout)

    _git("checkout", "--quiet", "-b", PATCHED_BRANCH, cwd=checkout)
    move_under_vendor(checkout)
    _git("add", "--all", "--", "_vendor", cwd=checkout)
    _git("commit", "--quiet", "-m", "Move Deep-Live-Cam under _vendor", cwd=checkout)
    _git("branch", BASE_BRANCH, cwd=checkout)

    for patch in find_patches():
        print(f"Applying {patch.name}", flush=True)
        try:
            _git("am", "--quiet", "--keep-cr", str(patch), cwd=checkout)
        except subprocess.CalledProcessError as error:
            raise PatchError(
                f"{patch.name} no longer applies to Deep-Live-Cam {commit[:12]}; resolve it "
                f"in {checkout}, run `git am --continue`, then `export` and `sync`"
            ) from error


def copy_out(checkout: Path, destination: Path) -> None:
    """Replace each of ``TREES`` under ``destination`` with the checkout's."""
    for tree in TREES:
        target = destination / tree
        if target.exists():
            _remove_tree(target)
        shutil.copytree(checkout / tree, target, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))


def sync(commit: str | None) -> None:
    commit = commit or resolve_commit()
    print(f"Deep-Live-Cam {commit}", flush=True)
    generate(commit, WORK_DIR)
    copy_out(WORK_DIR, REPO_ROOT)
    UPSTREAM_FILE.parent.mkdir(parents=True, exist_ok=True)
    UPSTREAM_FILE.write_text(commit + "\n", encoding="utf-8")


def _repository_files() -> set[Path]:
    """Files under ``TREES`` that git would commit: tracked or not ignored, and present."""
    output = subprocess.run(
        ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard", "--"]
        + [tree.as_posix() for tree in TREES],
        cwd=REPO_ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return {Path(name) for name in output.split("\0") if name and (REPO_ROOT / name).is_file()}


def _generated_files(root: Path) -> set[Path]:
    return {
        path.relative_to(root)
        for tree in TREES
        for path in (root / tree).rglob("*")
        if path.is_file() and "__pycache__" not in path.parts
    }


def _same(generated: Path, committed: Path) -> bool:
    """Byte-equal, but for CRLF line endings: a Windows checkout with
    ``core.autocrlf`` has them in the working tree, not in the repository."""
    a, b = generated.read_bytes(), committed.read_bytes()
    return a == b or a.replace(b"\r\n", b"\n") == b.replace(b"\r\n", b"\n")


def check() -> int:
    commit = UPSTREAM_FILE.read_text(encoding="utf-8").strip()
    with tempfile.TemporaryDirectory() as scratch:
        scratch_root = Path(scratch)
        generate(commit, scratch_root / "dlc")
        copy_out(scratch_root / "dlc", scratch_root / "out")
        generated = _generated_files(scratch_root / "out")
        committed = _repository_files()
        stale = sorted(
            [f"missing  {path.as_posix()}" for path in generated - committed]
            + [f"extra    {path.as_posix()}" for path in committed - generated]
            + [
                f"modified {path.as_posix()}"
                for path in generated & committed
                if not _same(scratch_root / "out" / path, REPO_ROOT / path)
            ],
            key=lambda line: line[9:],
        )
    for line in stale:
        print(line)
    if stale:
        print(
            f"The committed trees differ from Deep-Live-Cam {commit[:12]} plus the patches; "
            f"run `sync --commit {commit}` (and never edit _vendor/modules or "
            "_vendor/deep_live_cam by hand: see _vendor/README.md)",
            file=sys.stderr,
        )
        return 1
    print(f"_vendor is Deep-Live-Cam {commit[:12]} plus {len(find_patches())} patches.")
    return 0


def export() -> None:
    """Write the checkout's ``base..applio`` commits over the patch series.

    The series is replaced only once the new one is written: a checkout a
    failed ``sync`` left without ``base`` exports nothing, and deletes nothing.
    """
    with tempfile.TemporaryDirectory() as scratch:
        try:
            _git(
                "format-patch",
                "--quiet",
                "--zero-commit",
                "--no-signature",
                "--no-numbered",
                "-o",
                scratch,
                f"{BASE_BRANCH}..{PATCHED_BRANCH}",
                cwd=WORK_DIR,
            )
        except subprocess.CalledProcessError as error:
            raise PatchError(
                f"cannot export {BASE_BRANCH}..{PATCHED_BRANCH} from {WORK_DIR}; "
                "the patch series is left as it is"
            ) from error
        exported = find_patches(Path(scratch))
        if not exported:
            raise PatchError(
                f"{WORK_DIR} has no commits on {PATCHED_BRANCH} past {BASE_BRANCH}; "
                "the patch series is left as it is"
            )
        PATCHES_DIR.mkdir(parents=True, exist_ok=True)
        for patch in find_patches():
            patch.unlink()
        for patch in exported:
            shutil.move(patch, PATCHES_DIR / patch.name)
    for patch in find_patches():
        print(patch.relative_to(REPO_ROOT).as_posix())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    commands = parser.add_subparsers(dest="command", required=True)
    sync_parser = commands.add_parser("sync", help="regenerate _vendor/modules and _vendor/deep_live_cam")
    sync_parser.add_argument("--commit", help="Deep-Live-Cam commit (default: latest main)")
    commands.add_parser("check", help="fail if the committed trees are stale")
    commands.add_parser("export", help="write build/dlc's commits as patches")
    args = parser.parse_args(argv)
    try:
        if args.command == "sync":
            sync(args.commit)
        elif args.command == "check":
            return check()
        else:
            export()
    except PatchError as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
